// The Lanyard mark: two interlocked loops, the phone (upright) and the computer (wide), tied together.
// One definition; everything else (icons, favicon, site, Android vector) is generated from it.
export const COLORS = { bg: '#1b1006', orange: '#ff9a3c', cream: '#f6ead8' };
export const STROKE = 104;
export const A = { x: 250, y: 170, w: 320, h: 684, r: 160 }; // upright loop (phone), orange
export const B = { x: 400, y: 312, w: 380, h: 400, r: 170 }; // wide loop (computer), cream
// Where the orange loop passes over the cream one (the other crossing has cream over orange).
export const OVER = { x: 470, y: 230, w: 210, h: 170 };

const rect = (g) => `x="${g.x}" y="${g.y}" width="${g.w}" height="${g.h}" rx="${g.r}"`;

/** The mark alone, in a 1024 box, centred, on a transparent ground. */
export function markSvg(extra = '') {
  return `<g fill="none" stroke-width="${STROKE}" stroke-linecap="round" ${extra}>
    <rect ${rect(A)} stroke="${COLORS.orange}"/>
    <rect ${rect(B)} stroke="${COLORS.cream}"/>
    <rect ${rect(A)} stroke="${COLORS.orange}" clip-path="url(#over)"/>
  </g>`;
}
export const defs = `<defs><clipPath id="over"><rect x="${OVER.x}" y="${OVER.y}" width="${OVER.w}" height="${OVER.h}"/></clipPath></defs>`;

/** A full SVG document. `scale` shrinks the mark about the centre; `bg` is 'none' | 'square' | 'rounded' | 'macos'. */
export function svg({ bg = 'rounded', scale = 1, size = 1024 } = {}) {
  let ground = '';
  if (bg === 'square') ground = `<rect width="1024" height="1024" fill="${COLORS.bg}"/>`;
  if (bg === 'rounded') ground = `<rect width="1024" height="1024" rx="230" fill="${COLORS.bg}"/>`;
  if (bg === 'macos') ground = `<rect x="100" y="100" width="824" height="824" rx="185" fill="${COLORS.bg}"/>`;
  const s = bg === 'macos' ? scale * 0.8 : scale;
  const t = `translate(512 512) scale(${s}) translate(-512 -512)`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="${size}" height="${size}">${defs}${ground}<g transform="${t}">${markSvg()}</g></svg>`;
}

function roundedRectPath(g, s = 1, ox = 0, oy = 0) {
  const f = (n) => +(n * s).toFixed(2);
  const x = f(g.x) + ox, y = f(g.y) + oy, w = f(g.w), h = f(g.h), r = f(g.r);
  return `M${x + r},${y} H${x + w - r} A${r},${r} 0 0 1 ${x + w},${y + r} V${y + h - r} A${r},${r} 0 0 1 ${x + w - r},${y + h} H${x + r} A${r},${r} 0 0 1 ${x},${y + h - r} V${y + r} A${r},${r} 0 0 1 ${x + r},${y} Z`;
}

/** Android adaptive-icon foreground: a 108dp vector, the mark within the 66% safe zone. */
export function androidForeground() {
  const k = 108 / 1024 * 0.9; // 90% of the artwork box keeps it inside the safe zone
  const o = (108 - 1024 * k) / 2;
  const p = (g) => roundedRectPath(g, k, o, o);
  const sw = (STROKE * k).toFixed(2);
  const hex = (c) => c.toUpperCase();
  const over = `${(OVER.x * k + o).toFixed(2)},${(OVER.y * k + o).toFixed(2)} ${(OVER.x * k + o + OVER.w * k).toFixed(2)},${(OVER.y * k + o + OVER.h * k).toFixed(2)}`;
  const [a, b] = over.split(' ');
  const [x1, y1] = a.split(','); const [x2, y2] = b.split(',');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by brand/make-icons.mjs from brand/geometry.mjs. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:strokeColor="${hex(COLORS.orange)}" android:strokeWidth="${sw}" android:strokeLineCap="round" android:pathData="${p(A)}" />
    <path android:strokeColor="${hex(COLORS.cream)}" android:strokeWidth="${sw}" android:strokeLineCap="round" android:pathData="${p(B)}" />
    <group>
        <clip-path android:pathData="M${x1},${y1} H${x2} V${y2} H${x1} Z" />
        <path android:strokeColor="${hex(COLORS.orange)}" android:strokeWidth="${sw}" android:strokeLineCap="round" android:pathData="${p(A)}" />
    </group>
</vector>
`;
}
